// maxExampleLines trims long examples on the pages.
const maxExampleLines = 30

func writeSite(dir, testdata string, reg *registry.Registry) error {
	if err := os.MkdirAll(filepath.Join(dir, "tools"), 0o755); err != nil { //nolint:gosec // public docs
		return err
	}
	for _, t := range reg.All() {
		s := t.Spec()
		page, err := toolPage(s, filepath.Join(testdata, s.ID))
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(dir, "tools", s.ID+".md"), page); err != nil {
			return err
		}
	}
	return writeFile(filepath.Join(dir, "index.md"), indexPage(reg))
}

func writeFile(path, content string) error {
	return os.WriteFile(path, []byte(content), 0o644) //nolint:gosec // public docs
}

const generated = "<!-- Generated by cmd/gendocs from the registry and testdata; do not edit. -->\n\n"

func indexPage(reg *registry.Registry) string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# devtooltui\n\n")
	b.WriteString("Everyday developer utilities in a single binary: a keyboard-driven TUI and a\n")
	b.WriteString("CLI that composes with pipes. Install it and read the shortcuts in the\n")
	b.WriteString("[README](https://github.com/Judamaro/devtooltui-golang#readme).\n\n")
	fmt.Fprintf(&b, "## Tools (%d)\n", len(reg.All()))
	for _, g := range reg.ByCategory() {
		fmt.Fprintf(&b, "\n### %s\n\n| Tool | What it does |\n| --- | --- |\n", g.Category)
		for _, t := range g.Tools {
			s := t.Spec()
			fmt.Fprintf(&b, "| [%s](tools/%s.md) | %s |\n", s.Name, s.ID, escapeCell(s.Description))
		}
	}
	b.WriteString("\n## Design\n\n")
	b.WriteString("- [ADR 0001: Bubble Tea v2](adr/0001-bubbletea-v2.md)\n")
	b.WriteString("- [ADR 0002: large inputs](adr/0002-live-max-bytes.md)\n")
	b.WriteString("- [ADR 0003: what v1.0.0 keeps stable](adr/0003-v1-stability.md)\n")
	return b.String()
}

func toolPage(s tool.Spec, goldenDir string) (string, error) {
	var b strings.Builder
	b.WriteString(generated)
	fmt.Fprintf(&b, "# %s\n\n%s.\n\n", s.Name, strings.TrimSuffix(s.Description, "."))
	fmt.Fprintf(&b, "Category: %s · ID: `%s`", s.Category, s.ID)
	if len(s.Keywords) > 0 {
		fmt.Fprintf(&b, " · Search terms: %s", strings.Join(s.Keywords, ", "))
	}
	b.WriteString("\n\n## Command line\n\n```bash\n")
	b.WriteString(usage(s))
	b.WriteString("\n```\n")
	if len(s.Inputs) > 0 {
		b.WriteString("\n## Inputs\n\n")
		for i, in := range s.Inputs {
			fmt.Fprintf(&b, "%d. %s", i+1, in.Label)
			if len(s.Inputs) > 1 {
				fmt.Fprintf(&b, " (argument %d)", i+1)
			}
			b.WriteString("\n")
		}
	}
	if len(s.Options) > 0 {
		b.WriteString("\n## Options\n\n| Flag | Values | Default | Description |\n| --- | --- | --- | --- |\n")
		for _, o := range s.Options {
			fmt.Fprintf(&b, "| `--%s` | %s | `%v` | %s |\n", strings.ReplaceAll(o.Key, "_", "-"), values(o), o.Default,
				escapeCell(strings.TrimSpace(o.Label+". "+o.Help)))
		}
	}
	examples, err := examples(goldenDir)
	if err != nil {
		return "", err
	}
	if len(examples) > 0 {
		b.WriteString("\n## Examples\n\nFrom the tests (`testdata/" + s.ID + "`), so they are what the tool prints.\n")
		for _, e := range examples {
			fmt.Fprintf(&b, "\n### %s\n\n", e.name)
			if e.input != "" {
				b.WriteString("Input:\n\n" + fence(e.input) + "\nOutput:\n\n")
			}
			b.WriteString(fence(e.output))
		}
	}
	return b.String(), nil
}

func usage(s tool.Spec) string {
	cmd := "devtooltui " + s.ID
	for _, o := range s.Options {
		if o.Key == "mode" {
			cmd += " [" + strings.Join(o.Choices, "|") + "]"
		}
	}
	switch len(s.Inputs) {
	case 1:
		cmd += " [file|-]"
	case 2:
		cmd += " [file-A|-] [file-B|-]"
	}
	return cmd + " [flags]"
}

func values(o tool.Option) string {
	switch o.Kind {
	case tool.Toggle:
		return "on/off"
	case tool.Number:
		return fmt.Sprintf("%d–%d", o.Min, o.Max)
	case tool.Select:
		return "`" + strings.Join(o.Choices, "`, `") + "`"
	}
	return "text"
}

func escapeCell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

type example struct{ name, input, output string }

// examples pairs each golden with the .in it most likely came from: the
// same name, or the longest .in name that prefixes it.
func examples(dir string) ([]example, error) {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var ins, goldens []string
	for _, e := range entries {
		switch n := e.Name(); {
		case strings.HasSuffix(n, ".in"):
			ins = append(ins, strings.TrimSuffix(n, ".in"))
		case strings.HasSuffix(n, ".golden"):
			goldens = append(goldens, strings.TrimSuffix(n, ".golden"))
		}
	}
	slices.Sort(goldens)
	var out []example
	for _, g := range goldens {
		data, err := os.ReadFile(filepath.Join(dir, g+".golden")) //nolint:gosec // our testdata
		if err != nil {
			return nil, err
		}
		e := example{name: g, output: string(data)}
		best := ""
		for _, in := range ins {
			if (g == in || strings.HasPrefix(g, in+"-")) && len(in) > len(best) {
				best = in
			}
		}
		if best != "" {
			in, err := os.ReadFile(filepath.Join(dir, best+".in")) //nolint:gosec // our testdata
			if err != nil {
				return nil, err
			}
			e.input = string(in)
		}
		out = append(out, e)
	}
	return out, nil
}

// fence wraps text in a code block long enough for any backticks inside,
// trimmed to maxExampleLines.
func fence(s string) string {
	s = strings.TrimRight(s, "\n")
	lines := strings.Split(s, "\n")
	if len(lines) > maxExampleLines {
		lines = append(lines[:maxExampleLines], fmt.Sprintf("… (%d more lines)", len(lines)-maxExampleLines))
	}
	ticks := "```"
	for strings.Contains(s, ticks) {
		ticks += "`"
	}
	return ticks + "text\n" + strings.Join(lines, "\n") + "\n" + ticks + "\n"
}
